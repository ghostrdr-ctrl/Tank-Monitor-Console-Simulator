# "ASCII Hex IEEE float", which is how this manual writes every number. One
# encoder, in packed, under the name this module already calls it by.
_float = packed.hexfloat


def _stamp(when):
    """YYMMDDHHmm, or the manual's own ""0000000000" if no test yet"."""
    if not when:
        return "0000000000"
    return time.strftime("%y%m%d%H%M", time.localtime(when))


def _words(packed):
    """A packed stamp as the display format writes it, "DEC 22, 1995  3:31 PM"."""
    try:
        return clock_words(time.strptime(packed, "%y%m%d%H%M"))
    except ValueError:
        return packed


def _head(console, kind, number):
    """"Q 1:REGULAR UNLEADED", the line every one of these reports opens with."""
    label = console.text(LABEL[kind], number) or ""
    return f"{LETTER[kind]} {number}:{label}".rstrip()


def _display(handler, code, rows, tok):
    """The display format, with the station header where the manual shows one."""
    text = SEP.join(rows)
    if tok in HEADED:
        header = [t for t in (handler.c.text("503", n) for n in range(1, 5))
                  if t]
        if header:
            text = SEP.join(header) + SEP + text
    return handler._frame(code, text)


def _midnight(console):
    """The console's own midnight, which is what "SINCE MIDNIGHT" counts from."""
    t = console.now()
    return time.mktime((t.tm_year, t.tm_mon, t.tm_mday, 0, 0, 0, 0, 1, -1))


def _passes(console, kind, number, rate_key, since):
    """How many tests at that rate have passed on that line since then."""
    log = console.leaks.history.get((kind, number)) or []
    return sum(1 for r in log if r.rate_key == rate_key
               and r.result == leaktest.PASSED and r.started >= since)


def _alarms(console, kind, number, log):
    """The alarms standing against, or logged against, one line.

    "aaaa - type of alarm" is i10100's list numbered in hex where i10100
    numbers it in decimal, which is the same relation I206 has to it: PLLD
    Gross Test Fail Alarm is 21/02 on one and 0002 on the other.
    """
    want = CATEGORY[kind]
    if log:
        return [r for r in console.alarm_log
                if r["aa"] == want and r["tt"] == f"{number:02d}"]
    return [r for r in console.compute_alarms()
            if r[:2] == want and r[4:6] == f"{number:02d}"]


def _alarm_code(nn):
    return f"{int(nn):04X}" if nn.isdigit() else "0000"


def _alarm_text(aa, nn):
    return describe_alarms([aa + nn + "01"])[0]["description"].upper()


def _status_bits(console, ln, kind, number):
    """"SSSS - Status Bits", the three the manual defines and thirteen unused.

    "Bit 1 - (LSB) Dispensing enabled flag (0=Disabled, 1=Enabled), Bit 2 -
    Pump power (0=Pump Off, 1=Pump On), Bit 3 - Dispenser Handle (0=Handle
    Off, 1=Handle On)."
    """
    bits = 0
    if (kind, number) not in console.leaks.disabled:
        bits |= 1
    if ln.pump:
        bits |= 2
    if ln.handle:
        bits |= 4
    return f"{bits:04X}"


def _test_status(ln, kind):
    """(tt, the words that go with it) in whichever of the two tables applies."""
    if kind == "wplld":
        tt = WPLLD_STATUS_CODE.get(ln.status(), "00")
        return tt, WPLLD_STATUS[tt]
    tt = ln.status_code()
    return tt, PLLD_STATUS.get(tt, "TEST COMPLETE")


def _dispensing(console, kind, number):
    """"DISPENSING" column: what the shutdown output is doing to the line."""
    return "DISABLED" if (kind, number) in console.leaks.disabled else "ENABLED"


def _line_row(console, ln, kind, number):
    """One row of the status table 381, 386, B81 and B82 all share."""
    _tt, words = _test_status(ln, kind)
    return (f"{_head(console, kind, number):<25.25s}"
            f"{_dispensing(console, kind, number):<12s}{words:<22s}"
            f"{'ON' if ln.pump else 'OFF':<6s}"
            f"{'ON' if ln.handle else 'OFF'}")


LINE_HEADER = (f"{'LINE':<25s}{'DISPENSING':<12s}{'TEST STATUS':<22s}"
               f"{'PUMP':<6s}HANDLE")


def _no_vent(ln):
    """"NO-VENT TEST ABORTS: 3 OUT OF 10 TESTS".

    "Test aborts if Pon = P1 (P1 should be lower since pump is shut off before
    P1 is measured)", so the count is every measurement whose Pon and P1 came
    out the same. 373 and 388 print one figure for the line rather than one
    per rate, so every measurement the line holds is counted.
    """
    rows = (ln.readings["gross"] + ln.readings["mid"]
            + ln.cycles["periodic"] + ln.cycles["annual"])
    return sum(1 for r in rows if abs(r.pon - r.p1) < 0.001), len(rows)


def _result_word(result):
    """"JAN 24, 1996 2:49 PM PASS", which is how these reports print a verdict."""
    if result is None:
        return "NO TEST DATA AVAILABLE"
    word = {leaktest.PASSED: "PASS", leaktest.FAILED: "FAIL"}.get(
        result.result, "INVALID")
    return f"{clock_words(result.started)} {word}"


