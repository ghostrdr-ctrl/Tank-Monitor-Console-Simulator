# B87 and B8B print three blocks, B88 and B8C two: "RR - Test result type,
# 00=Pass, 01=Fail, 02=Hi-pressure events", and a mid-range test has no
# high pressure event of its own to report.
PUMPOFF_WHICH = {"B87": "gross", "B8B": "gross", "B88": "mid", "B8C": "mid"}


def _pumpoff_diagnostic(handler, code, kind, lines, tok):
    """B87, B88, B8B and B8C: the pump-Off tests, in passes, fails and events.

    "LL - Total Events to follow (Max=5 each)" over three groups of
    "YYMMDDHHmm aaaaaaaa bbbbbbbb cccccccc": the date, "Pump on pressure
    read", "First pressure read" and "Second pressure read", which are Pon,
    P1 and P2 as 577013-344 names them. The console's own 3.0 DIAG printout
    groups the same records the same way: "This report contains the last 5
    test passes, fails, and high pressure events."
    """
    c = handler.c
    which = PUMPOFF_WHICH[tok]
    name = "3.0" if which == "gross" else "MID"
    title = ("WPLLD LINE LEAK DIAGNOSTIC REPORT" if kind == "wplld"
             else "PRESSURE LINE LEAK DIAGNOSTIC REPORT")
    header = (f"{'DATE/TIME':<24s}{'PUMP ON':>9s}{'FIRST READ':>13s}"
              f"{'SECOND READ':>13s}")
    rows, body = [title, ""], ""
    for number in lines:
        ln = c.lines.line(kind, number)
        held = ln.readings[which][-30:]
        blocks = [(DIAG_PASS, f" {name} TEST PASSES",
                   [r for r in held if r.passed and not r.high]),
                  (DIAG_FAIL, f" {name} TEST FAILS",
                   [r for r in held if r.passed is False and not r.high])]
        if which == "gross":
            # "High Pressure Event Thresholds: Pon > 50 psi"
            blocks.append((DIAG_HIGH, f" {name} HI PRESSURE EVENTS",
                           [r for r in held if r.high]))
        rows.append(_head(c, kind, number))
        body += f"{number:02d}"
        for result_type, label, records in blocks:
            records = records[-5:]
            rows += ["", label, header]
            for r in records:
                rows.append(f"{clock_words(r.when):<24s}{r.pon:5.1f} PSI"
                            f"{r.p1:9.1f} PSI{r.p2:9.1f} PSI")
            if not records:
                rows.append("NO TEST DATA AVAILABLE")
            body += f"{result_type}{len(records):02X}"
            body += "".join(_stamp(r.when) + _float(r.pon) + _float(r.p1)
                            + _float(r.p2) for r in records)
        rows.append("")
    if code[0].isupper():
        return _display(handler, code, rows, tok), f"{name.lower()} test diagnostic"
    return handler._frame(code, body), f"{name.lower()} test diagnostic"


PRECISION_WHICH = {"B89": "periodic", "B8D": "periodic",
                   "B8A": "annual", "B8E": "annual"}


def _precision_diagnostic(handler, code, kind, lines, tok):
    """B89, B8A, B8D and B8E: the last ten leak rates, as ratios.

    "LL - Total Tests to follow (Max=10)" then "YYMMDDHHmm RR aaaaaaaa
    bbbbbbbb cccccccc": the date, "00=Pass, 01=Fail", "Pump on pressure read,
    PSI", "Fail ratio" and "Duration (in minutes)". The ratio is the verdict
    on its own, "Ratio <1 Pass, >1 Fail", which is why the report carries it
    instead of the rate.

    "For User Defined Pipe Types PUMP ON will be PMID", so the column heading
    follows the pipe the line is programmed with.
    """
    c = handler.c
    which = PRECISION_WHICH[tok]
    rate = RATE_NAME[which]
    title = ("WPLLD LINE LEAK DIAGNOSTIC REPORT" if kind == "wplld"
             else "PRESSURE LINE LEAK DIAGNOSTIC REPORT")
    rows, body = [title, ""], ""
    for number in lines:
        ln = c.lines.line(kind, number)
        held = ln.cycles[which][-10:]
        pump_on = ("PMID" if _pipe_key(c, kind, number) == USER_DEFINED
                   else "PUMP ON")
        rows += [_head(c, kind, number), f"{rate} TEST RESULTS",
                 f"{'DATE/TIME':<22s}{pump_on:>9s}{'RATIO':>8s}"
                 f"{'DURATION':>10s}  RESULTS"]
        for r in held:
            rows.append(f"{clock_words(r.when):<22s}{r.pon:5.1f} PSI"
                        f"{r.ratio:8.2f}{r.minutes:10d}  "
                        + ("PASSED" if r.passed else "FAILED"))
        if not held:
            rows.append("NO TEST DATA AVAILABLE")
        rows.append("")
        body += f"{number:02d}{len(held):02X}"
        body += "".join(_stamp(r.when)
                        + (DIAG_PASS if r.passed else DIAG_FAIL)
                        + _float(r.pon) + _float(r.ratio) + _float(r.minutes)
                        for r in held)
    if code[0].isupper():
        return _display(handler, code, rows, tok), f"{rate} test diagnostic"
    return handler._frame(code, body), f"{rate} test diagnostic"


