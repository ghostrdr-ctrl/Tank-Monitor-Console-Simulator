def _pumpside(console, number):
    """S758: "PUMPSIDE TEST: ENABLED", "ss - 01=Enable"."""
    raw = (console.values.get(f"S758{number:02d}") or "").strip()
    return raw.endswith("1")


def _recent(console, number, rate_key, most=3):
    """The precision tests 351 lists, newest first.

    The manual's sample prints three dates under each rate and its computer
    format carries a count, so three is the depth the report is drawn at.
    """
    log = console.leaks.history.get(("vlld", number)) or []
    return [r for r in reversed(log) if r.rate_key == rate_key][:most]


def _vlld_results(handler, code, kind, lines, tok):
    """351: the 3.0 counts in three columns, then the precision test dates.

    "LL - 3.00 GPH Line tests passed in previous 24 hours", "SS - 3.00 GPH
    Self tests passed", "BB - 3.00 GPH Pumpside tests passed", then the same
    three since midnight.

    The self test is not a test of its own: "A Self test checks for improper
    switch conditions THROUGHOUT the Line Leak test", so it passes whenever
    the line test it rode on passed, and deriving it is correct.

    The pumpside test is NOT derived, and used to be. It measures "the piping
    and connections between the in-line check valve and the submersible
    pump", which is a different piece of pipe from the one the line test just
    measured, so its count comes from its own results. A line that passes
    over a leaking pump-side joint reports LINE 1 PUMP 0, which is the whole
    reason the test exists.
    """
    c = handler.c
    now = time.mktime(c.now())
    windows = (now - 86400.0, _midnight(c))
    rows, body = [], ""
    for number in lines:
        counts = []
        for since in windows:
            line = _passes(c, "vlld", number, "gross", since)
            pump = c.leaks.pumpside_passes(number, "gross", since)
            counts.append((line, line, pump))
        periodic = _recent(c, number, "periodic")
        annual = _recent(c, number, "annual")
        rows.append(_head(c, "vlld", number))
        rows.append(f"{'3.0 GAL/HR TEST':<27s}{'LINE':>5s}{'SELF':>6s}"
                    f"{'PUMP':>6s}")
        for name, (line, self_, pump) in zip(("PREV 24 HOURS",
                                              "SINCE MIDNIGHT"), counts):
            rows.append(f"           {name:<16s}{line:5d}{self_:6d}{pump:6d}")
        for name, results in (("0.2 GAL/HR TEST", periodic),
                              ("0.1 GAL/HR TEST", annual)):
            rows.append(name)
            for r in results:
                rows.append(f"           {clock_words(r.started):<24s}"
                            f"{r.result}")
            if not results:
                rows.append("           NO TEST DATA AVAILABLE")
        body += f"{number:02d}"
        for line, self_, pump in counts:
            body += f"{min(line, 255):02X}{min(self_, 255):02X}" \
                    f"{min(pump, 255):02X}"
        for results in (periodic, annual):
            body += f"{len(results):02d}"
            for r in results:
                body += _stamp(r.started) + VLLD_PASS_FAIL.get(r.result, "00")
    if code[0].isupper():
        return _display(handler, code, rows, tok), "volumetric line results"
    return handler._frame(code, body), "volumetric line results"


def _line_alarm_history(handler, code, kind, lines, tok):
    """352, 382 and 387: every alarm this line has raised, with its date.

    "NN - Number of Alarm entries to follow (Decimal)" in 352 and
    "NN - number of alarms to follow (Hex)" in 382 and 387, which is the same
    two characters for any count a console keeps.
    """
    c = handler.c
    titles = {"352": "", "382": "PRESSURE LINE LEAK ALARM HISTORY REPORT",
              "387": "WPLLD LINE LEAK ALARM HISTORY REPORT"}
    rows = [titles[tok], ""] if titles[tok] else []
    body = ""
    for number in lines:
        records = _alarms(c, kind, number, log=True)
        rows.append(_head(c, kind, number))
        for r in records:
            rows.append(f"   {_words(r['at']):<22s}"
                        f"{_alarm_text(r['aa'], r['nn'])}")
        if not records:
            rows.append("   NO ALARM HISTORY")
        rows.append("")
        count = (f"{len(records):02d}" if tok == "352"
                 else f"{min(len(records), 255):02X}")
        body += f"{number:02d}{count}"
        body += "".join(r["at"] + _alarm_code(r["nn"]) for r in records)
    if code[0].isupper():
        return _display(handler, code, rows, tok), "line alarm history"
    return handler._frame(code, body), "line alarm history"


def _vlld_pump_status(handler, code, kind, lines, tok):
    """353: "aaaa - Line Status: 0001=Enabled, 0002=Disabled"."""
    c = handler.c
    rows = [f"{'LINE':<11s}{'LOCATION':<22s}STATUS"]
    body = ""
    for number in lines:
        down = ("vlld", number) in c.leaks.disabled
        label = c.text(LABEL["vlld"], number) or ""
        rows.append(f"{number:5d}      {label:<22.22s}"
                    + ("DISABLED" if down else "ENABLED"))
        body += f"{number:02d}" + ("0002" if down else "0001")
    if code[0].isupper():
        return _display(handler, code, rows, tok), "line pump status"
    return handler._frame(code, body), "line pump status"


