def _vlld_tank(console, number):
    """S752, "Set Volumetric Line Leak Tank Number"."""
    raw = (console.values.get(f"S752{number:02d}") or "").strip()
    body = raw[2:] if len(raw) > 2 else raw
    return int(body) if body.isdigit() else 0


def _vlld_switches(console, number):
    """The eight signals B50 draws, from the two things the model knows.

    THE MAPPING IS THE SIMULATOR'S OWN. What is real is whether a test is
    running and whether the line has been shut down; a volumetric controller's
    switches are not modelled anywhere in this simulator, because a VLLD test
    here is a stopwatch over a result rather than a mechanical detector.

    The mapping is the one the manual's own sample implies. Its line is idle
    and disabled, and reads PMP IN=OFF PMP OUT=OFF, PRS SW=ON, EQU VLV=OFF,
    FIN SW=OFF, TST VLV=OFF, STR SW=ON, DISABLE=ON: so at rest the line holds
    pressure and the start switch is made, the pump signals and both valves
    are off, and DISABLE follows the shutdown.
    """
    running = console.leaks.active("vlld", number) is not None
    down = ("vlld", number) in console.leaks.disabled
    pump_in = running
    pump_out = running and not down
    return {"pump_in": pump_in, "pressure": True, "final": running,
            "start": True, "pump_out": pump_out, "equalise": running,
            "test": running, "disable": down}


def _on(flag):
    """" ON" or "OFF", right aligned in three, as the B50 screen draws them."""
    return " ON" if flag else "OFF"


def _vlld_status(handler, code, kind, lines, tok):
    """B50: four rows of two signals each, in the order the notes number them."""
    c = handler.c
    rows, body = [], ""
    for number in lines:
        s = _vlld_switches(c, number)
        rows.append(_head(c, "vlld", number))
        rows.append(f"   PMP IN={_on(s['pump_in'])} "
                    f"PMP OUT={_on(s['pump_out'])}")
        rows.append(f"   PRS SW={_on(s['pressure'])} "
                    f"EQU VLV={_on(s['equalise'])}")
        rows.append(f"   FIN SW={_on(s['final'])} "
                    f"TST VLV={_on(s['test'])}")
        rows.append(f"   STR SW={_on(s['start'])} "
                    f"DISABLE={_on(s['disable'])}")
        rows.append("")
        body += f"{number:02d}"
        for key in ("pump_in", "pressure", "final", "start", "pump_out",
                    "equalise", "test", "disable"):
            body += "01" if s[key] else "00"
    if code[0].isupper():
        return _display(handler, code, rows, tok), "volumetric line status"
    return handler._frame(code, body), "volumetric line status"


def _vlld_timings(console, number, result):
    """The six columns B51 and B52 print that this simulator does not model.

    GENERATED, per readings.py's rule: stable per line and per test, in the
    bands the manual's own samples print. "DDDD - Minutes since dispenser off"
    runs 0 to 81 across the two samples, "LLLL - Allowed tenths of a second for
    Final Switch to actuate" 10.0 to 794.0, "RRRR - Tenths of a second for
    Start Switch to close" 0.0 to 4.9, and "TTTT - Actual tenths of a second
    for Final Switch to actuate" 5.3 to 326.0. The actual can never exceed the
    allowed on a test that passed, which is what the allowance is for.

    The two temperatures are not generated: the tank's is the probe's own
    reading for the tank this line is programmed to, and the ground sits a
    little above it, which is the relation both samples show (46.9 over 45.9,
    45.3 over 45.4).
    """
    tank = _vlld_tank(console, number)
    tank_temp = console.product_temperature(tank or number)
    ground = tank_temp + readings.fixed(-1.0, 1.6, "grnd", number)
    key = ("vlld", number, result.started)
    allowed = readings.fixed(10.0, 794.0, "lgth", *key)
    actual = readings.fixed(5.3, 326.0, "final", *key)
    if result.result == leaktest.PASSED:
        actual = min(actual, allowed)
    return (ground, tank_temp,
            readings.integer(0, 81, "dely", *key), allowed,
            readings.fixed(0.0, 4.9, "reset", *key), actual)


def _vlld_diag_history(handler, code, kind, lines, tok):
    """B51 and B52: the gross tests, and the two precision rates.

    Both are the same record, "YYMMDDHHmmTTg..gt..tDDDDLLLLRRRRTTTTrr", and
    differ only in which tests are in it. The TYP column is the manual's own
    quartet numbering, and this simulator runs the line test of each quartet.
    """
    c = handler.c
    wanted = ("gross",) if tok == "B51" else ("periodic", "annual")
    header = (f"{'DATE/TIME':<22s}{'TYP':>3s}{'GRND':>7s}{'TANK':>7s}"
              f"{'DELY':>6s}{'LGTH':>8s}{'RSET':>7s}{'TEST':>8s}  RSLT")
    rows, body = [], ""
    for number in lines:
        log = [r for r in reversed(c.leaks.history.get(("vlld", number)) or [])
               if r.rate_key in wanted]
        rows += [_head(c, "vlld", number), header]
        block = ""
        for r in log:
            typ = VLLD_LINE_TEST[r.rate_key]
            grnd, tank, dely, allowed, reset, actual = _vlld_timings(
                c, number, r)
            rows.append(f"{clock_words(r.started):<22s}{typ:3d}{grnd:7.1f}"
                        f"{tank:7.1f}{dely:6d}{allowed:8.1f}{reset:7.1f}"
                        f"{actual:8.1f}  {r.result}")
            # the wire's timings are a 16-bit count of tenths of a second
            # where the printout carries a decimal place, so they round
            block += (_stamp(r.started) + f"{typ:02X}" + _float(grnd)
                      + _float(tank) + f"{min(dely, 0xFFFF):04X}"
                      + f"{round(allowed):04X}{round(reset):04X}"
                      + f"{round(actual):04X}"
                      + leaktest.RESULT_CODE[r.result])
        if not log:
            rows.append("NO TEST DATA AVAILABLE")
        rows.append("")
        body += f"{number:02d}{len(log):02d}" + block
    if code[0].isupper():
        return _display(handler, code, rows, tok), "volumetric line diagnostic"
    return handler._frame(code, body), "volumetric line diagnostic"


