def handle(handler, tok, dev, code, data):
    """Answer one function code, or return None if it is not ours."""
    kind = KIND.get(tok)
    if kind is None:
        return None
    if not handler.c.has(kind):
        # a card that is not in the cage is a function this console does not
        # have, which is the same answer as a function it has never heard of
        return handler._nine(code), f"no {kind} module fitted"
    # "QQ - Pressure Line Leak sensor number (Decimal, 00=All)", and the same
    # note heads every report in this family. "All" is all the lines the
    # console HAS, which is what `programmed_lines` means by one: a PLLD
    # controller takes six transducers and a site that wired two has two
    # lines, and reporting TEST COMPLETE against four pieces of pipe nobody
    # configured is reporting on a site that does not exist.
    #
    # A cage with the card in it and nothing programmed still has to answer,
    # because "a function code that it does not recognize" is not what this
    # is, so it answers on the card's first position, where every one of
    # these reports has a NO TEST DATA AVAILABLE to print.
    if dev != "00" and dev.isdigit() and int(dev):
        lines = [int(dev)]
    else:
        lines = [n for k, n, _label in handler.c.programmed_lines()
                 if k == kind]
        if not lines:
            lines = handler._devices_of(kind, dev)[:1]
    return REPORTS[tok](handler, code, kind, lines, tok)
