def _diameter(gallons_per_foot):
    """Inches, from the gallons a foot of that pipe holds.

    A gallon is 231 cubic inches, so a foot of pipe holding g gallons has a
    bore of 231g/12 square inches, and the diameter follows. The Application
    Guide publishes the volume rather than the bore, so this is the bore it
    published: 0.190 gal/ft comes back as 2.16 inches, which is 2 inch pipe.
    """
    area = 231.0 * gallons_per_foot / 12.0
    return math.sqrt(4.0 * area / math.pi)


def _pipe_key(console, kind, number):
    """The S788 piping-material enumeration this line is programmed with."""
    code = "788" if kind == "plld" else "7A8"
    raw = (console.values.get(f"S{code}{number:02d}") or "").strip()
    return raw[-2:] if len(raw) >= 2 else pressure.DEFAULT_PIPE


def _profile_line_test(handler, code, kind, lines, tok):
    """B7B: the seven floats the profile line test leaves behind.

    Every one of them has a setup function of its own, so this reports what
    the console was told rather than anything it invented: 779 Primary Pipe
    Bulk Modulus, 775 Profile Line Test Leak Rate, 776 Profile Line Test
    Reference Pressure, 789 Primary Pipe Length, 777 Primary Pipe Diameter,
    77F Secondary Pipe Length and 778 Secondary Pipe Diameter, in the order
    note 6 lists them.

    "a - Valid profile line test flag, 0=profile line test invalid,
    1=profile line test valid": the test's whole output is the bulk modulus it
    measures, so a line with one programmed at 779 has had one and a line
    without has not.
    """
    c = handler.c
    rows, body = ["PRESSURE LINE LEAK PROFILE LINE TEST", ""], ""
    for number in lines:
        ln = c.lines.line(kind, number)
        measured = c.limit("779", number)
        modulus = measured or ln.pipe()[0]
        when = c._commissioned if measured else None
        key = _pipe_key(c, kind, number)
        values = [modulus,
                  c.limit("775", number) or 0.0,
                  c.limit("776", number) or ln.engine.pump_psi(kind, number),
                  c.limit("789", number) or ln.length(),
                  c.limit("777", number) or _diameter(ln.pipe()[1]),
                  c.limit("77F", number) or 0.0,
                  c.limit("778", number) or 0.0]
        rows += [_head(c, kind, number),
                 "LAST PROFILE LINE TEST: "
                 + (clock_words(when) if when else "NONE"),
                 f"BULK MODULUS: {values[0]:.0f} PSI",
                 f"TEST LEAK RATE: {values[1]:.2f} GPH",
                 f"REF PRESSURE: {values[2]:.2f} PSI", "",
                 "TYP:" + PIPE_NAME.get(key, PIPE_NAME[pressure.DEFAULT_PIPE]),
                 f"1ST LINE  LEN :{values[3]:.0f} FEET",
                 f"2ND LINE  LEN :{values[5]:.0f} FEET",
                 f"1ST LINE  DIAM: {values[4]:.2f} IN.",
                 f"2ND LINE  DIAM: {values[6]:.2f} IN.", ""]
        body += (f"{number:02d}" + ("1" if measured else "0") + _stamp(when)
                 + key + f"{len(values):02X}"
                 + "".join(_float(v) for v in values))
    if code[0].isupper():
        return _display(handler, code, rows, tok), "profile line test"
    return handler._frame(code, body), "profile line test"


