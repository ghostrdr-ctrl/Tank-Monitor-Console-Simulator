def _samples(ln, most=14):
    """The pressures B82 lists as P 0 to P13, newest first.

    A WPLLD transducer sends its readings up by radio and the console keeps
    the last of them; the sample printout shows every slot as -99.000, which
    is a console holding none. So the slots are filled from the measurements
    this line has actually taken, newest first, and the rest stay empty.
    """
    out = []
    records = sorted(ln.readings["gross"] + ln.readings["mid"]
                     + ln.cycles["periodic"] + ln.cycles["annual"],
                     key=lambda r: r.when, reverse=True)
    for r in records:
        out += [r.p2, r.p1, r.pon]
        if len(out) >= most:
            break
    return (out + [NO_READING] * most)[:most]


