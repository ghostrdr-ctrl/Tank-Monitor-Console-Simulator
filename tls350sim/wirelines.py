def _offset_monitor(handler, code, kind, lines, tok):
    """B7E and B7F: the three monitors of Figure 13 of 577013-344.

    Its terms are the guide's own: "P0 = Line pressure w/pump off (< 5 psi),
    Pd = Pump pressure during dispense, Pv = Pump vent pressure", and
    "Pv = P2 measured in last gross test" over "Pon = pump on pressure
    measured in last gross test".

    "The PO state will always be pass." Pd fails when it has stood more than
    Pd Ref + 5 psi for longer than thirty days, and Pv fails on the vent
    pressure monitor's own rule, "If Pv > 40 psi and Pd > 50 psi".

    The two day counters are GENERATED: nothing here logs when a line last sat
    below 5 psi or when Pd last came back inside its reference, and the guide
    prints 21 and 51 days for them.
    """
    c = handler.c
    title = ("WPLLD LINE LEAK PRESSURE OFFSET MONITORS REPORT"
             if kind == "wplld"
             else "PRESSURE LINE LEAK PRESSURE OFFSET MONITORS REPORT")
    rows, body = [title, ""], ""
    for number in lines:
        ln = c.lines.line(kind, number)
        # Pd Ref is "locked into" the pump's own pressure at startup, so it is
        # this line's nominal, and Pd is what the pump is reading now.
        reference = c.limit("7B7", number) or readings.fixed(
            pressure.PUMP_PSI - 4.0, pressure.PUMP_PSI + 6.5,
            "pump", kind, number)
        pd = c.lines.pump_psi(kind, number)
        last = (ln.readings["gross"] or [None])[-1]
        pv = last.p2 if last else 0.0
        pon = last.pon if last else 0.0
        p0_days = readings.integer(0, 60, "p0days", kind, number)
        pd_days = (0 if pd <= reference + PD_MARGIN
                   else readings.integer(0, 60, "pddays", kind, number))
        pd_ok = pd_days <= PD_DAYS
        pv_ok = not (pv > PV_LIMIT and pd > PD_LIMIT)
        rows += [_head(c, kind, number),
                 "   P0: PASS",
                 f"       LAST UPDATE: {p0_days}     DAYS",
                 "   Pd: " + ("PASS" if pd_ok else "FAIL"),
                 f"       LAST UPDATE: {pd_days}     DAYS",
                 f"       Pd= {pd:.1f} PSI",
                 f"       Pd Ref={reference:.1f} PSI",
                 "   Pv: " + ("PASS" if pv_ok else "FAIL"),
                 f"       Pv ={pv:.1f} PSI",
                 f"       Pon={pon:.1f} PSI",
                 f"       Pd ={pd:.1f} PSI", ""]
        body += (f"{number:02d}01{min(p0_days, 0xFFFF):04X}"
                 + ("01" if pd_ok else "00")
                 + f"{min(pd_days, 0xFFFF):04X}" + _float(pd)
                 + _float(reference) + ("01" if pv_ok else "00")
                 + _float(pv) + _float(pon) + _float(pd))
    if code[0].isupper():
        return _display(handler, code, rows, tok), "pressure offset monitors"
    return handler._frame(code, body), "pressure offset monitors"


